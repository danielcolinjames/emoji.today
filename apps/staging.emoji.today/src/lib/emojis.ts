// Simplified emoji utilities for staging app
// Note: In production, this would import from @emoji.today/emoji-assets package

export function getEmojiImageUrl(emoji: string) {
  if (!emoji || emoji === "") {
    return null
  }
  const codePoints = Array.from(emoji).map((char) =>
    char.codePointAt(0)!.toString(16).padStart(4, "0")
  )
  const emojiCode = codePoints.join("-")

  // Use local emoji assets - these would need to be added to public/emoji-assets/
  return `/emoji-assets/apple-160/${emojiCode}.png`
}

